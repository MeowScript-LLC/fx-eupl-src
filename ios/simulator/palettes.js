class CRGBPalette16 {
  constructor(entries) {
    this.entries = new Array(16);
    if (entries) {
      for (let i = 0; i < 16; i++) this.entries[i] = entries[i] || [0,0,0];
    } else {
      for (let i = 0; i < 16; i++) this.entries[i] = [0,0,0];
    }
  }

  static fromGradientStops(stops) {
    const pal = new CRGBPalette16();
    for (let i = 0; i < 16; i++) {
      const pos = (i * 255) / 15;
      let lo = stops[0], hi = stops[stops.length - 1];
      for (let j = 0; j < stops.length - 1; j++) {
        if (stops[j][0] <= pos && stops[j + 1][0] >= pos) {
          lo = stops[j]; hi = stops[j + 1]; break;
        }
      }
      const range = hi[0] - lo[0];
      const t = range > 0 ? (pos - lo[0]) / range : 0;
      pal.entries[i] = [
        Math.round(lo[1] + (hi[1] - lo[1]) * t),
        Math.round(lo[2] + (hi[2] - lo[2]) * t),
        Math.round(lo[3] + (hi[3] - lo[3]) * t),
      ];
    }
    return pal;
  }

  static fromEntries(entries) {
    const pal = new CRGBPalette16();
    for (let i = 0; i < 16; i++) pal.entries[i] = entries[i].slice();
    return pal;
  }

  colorAt(index, brightness = 255, blendType = 1) {
    index = index & 0xFF;
    if (blendType === 2) index = (index * (1 + 0xF0)) >> 8;

    const hi4 = (index >> 4) & 0xF;
    const lo4 = index & 0x0F;

    const e1 = this.entries[hi4];
    let r = e1[0], g = e1[1], b = e1[2];

    if (lo4 > 0 && blendType !== 0) {
      const e2 = this.entries[(hi4 + 1) & 0xF];
      const f2 = lo4 << 4;
      const f1 = 256 - f2;
      r = (r * f1 + e2[0] * f2) >> 8;
      g = (g * f1 + e2[1] * f2) >> 8;
      b = (b * f1 + e2[2] * f2) >> 8;
    }

    if (brightness < 255) {
      const s = brightness + 1;
      r = (r * s) >> 8;
      g = (g * s) >> 8;
      b = (b * s) >> 8;
    }

    return ((r & 0xFF) << 16) | ((g & 0xFF) << 8) | (b & 0xFF);
  }
}

class PaletteManager {
  constructor() {
    this._cache = {};
    this._randomPalette = null;
    this._randomPaletteTime = 0;
  }

  getPalette(paletteId, segColors = [0xFFAA00, 0, 0]) {
    if (paletteId <= 5) return this._buildDynamicPalette(paletteId, segColors);
    if (this._cache[paletteId]) return this._cache[paletteId];

    if (FASTLED_PALETTES[paletteId]) {
      const pal = CRGBPalette16.fromEntries(FASTLED_PALETTES[paletteId].entries);
      this._cache[paletteId] = pal;
      return pal;
    }

    if (GRADIENT_PALETTE_DEFS[paletteId]) {
      const pal = CRGBPalette16.fromGradientStops(GRADIENT_PALETTE_DEFS[paletteId].stops);
      this._cache[paletteId] = pal;
      return pal;
    }

    return this.getPalette(11, segColors);
  }

  _buildDynamicPalette(id, colors) {
    const M = (typeof WLEDMath !== 'undefined') ? WLEDMath : window.WLEDMath;
    const c0 = colors[0] || 0xFFAA00, c1 = colors[1] || 0, c2 = colors[2] || 0;
    const rgb = (c) => [(c >> 16) & 0xFF, (c >> 8) & 0xFF, c & 0xFF];
    const [r0,g0,b0] = rgb(c0), [r1,g1,b1] = rgb(c1), [r2,g2,b2] = rgb(c2);
    const pal = new CRGBPalette16();

    switch (id) {
      case 0: {
        return this.getPalette(6, colors);
      }
      case 1: {
        const now = M.getNow();
        if (!this._randomPalette || (now - this._randomPaletteTime > 5000)) {
          for (let i = 0; i < 16; i++) {
            const c = M.color_wheel(Math.floor(Math.random() * 256));
            pal.entries[i] = [(c >> 16) & 0xFF, (c >> 8) & 0xFF, c & 0xFF];
          }
          this._randomPalette = pal;
          this._randomPaletteTime = now;
        }
        return this._randomPalette;
      }
      case 2:
        for (let i = 0; i < 16; i++) pal.entries[i] = [r0,g0,b0];
        return pal;
      case 3:
        for (let i = 0; i < 16; i++) {
          let r, g, b;
          if (i <= 5) { r = r0; g = g0; b = b0; }
          else if (i <= 10) {
            const s = (i - 5) / 5;
            r = r0 + (r1-r0)*s; g = g0 + (g1-g0)*s; b = b0 + (b1-b0)*s;
          } else { r = r1; g = g1; b = b1; }
          pal.entries[i] = [Math.round(r), Math.round(g), Math.round(b)];
        }
        return pal;
      case 4: {
        const seq = [c2,c2,c1,c1,c1,c0,c0,c0,c2,c2,c1,c1,c0,c0,c2,c2];
        for (let i = 0; i < 16; i++) pal.entries[i] = rgb(seq[i]);
        return pal;
      }
      case 5:
        for (let i = 0; i < 16; i++) {
          if (c2 !== 0) {
            if (i < 5) pal.entries[i] = [r0,g0,b0];
            else if (i < 10) pal.entries[i] = [r1,g1,b1];
            else if (i < 15) pal.entries[i] = [r2,g2,b2];
            else pal.entries[i] = [r0,g0,b0];
          } else {
            pal.entries[i] = i < 8 ? [r0,g0,b0] : [r1,g1,b1];
          }
        }
        return pal;
      default:
        return this.getPalette(6, colors);
    }
  }

  colorFromPalette(paletteId, index, brightness = 255, segColors = [0xFFAA00, 0, 0], blendType = 1) {
    const pal = this.getPalette(paletteId, segColors);
    return pal.colorAt(index, brightness, blendType);
  }

  getPaletteName(id) {
    if (id <= 5) return ["Default","* Random Cycle","* Color 1","* Colors 1&2","* Color Gradient","* Colors Only"][id];
    if (FASTLED_PALETTES[id]) return FASTLED_PALETTES[id].name;
    if (GRADIENT_PALETTE_DEFS[id]) return GRADIENT_PALETTE_DEFS[id].name;
    return `Palette ${id}`;
  }

  getAllPaletteIds() {
    const ids = new Set();
    for (let i = 0; i <= 5; i++) ids.add(i);
    for (const k in FASTLED_PALETTES) ids.add(parseInt(k));
    for (const k in GRADIENT_PALETTE_DEFS) ids.add(parseInt(k));
    return [...ids].sort((a, b) => a - b);
  }

  getPaletteCSS(paletteId, segColors) {
    const pal = this.getPalette(paletteId, segColors);
    const stops = [];
    for (let i = 0; i < 16; i++) {
      const [r, g, b] = pal.entries[i];
      stops.push(`rgb(${r},${g},${b}) ${Math.round(i/15*100)}%`);
    }
    return `linear-gradient(to right, ${stops.join(', ')})`;
  }

  clearCache() { this._cache = {}; }
}

